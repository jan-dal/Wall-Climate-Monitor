<p class="note method-note">
  <strong>How estimates work:</strong> Dew point is calculated from AHT20 air temperature
  and humidity using the Magnus approximation. Estimated surface RH assumes the
  water-vapor pressure at the wall is approximately the same as in the nearby air,
  and uses the DS18B20 wall-surface temperature. Displayed surface RH is capped
  at 100%; a cap indicates saturation/possible condensation, not a measured
  amount of liquid water. Condensation margin = wall temperature − dew point;
  values at or below 0°C indicate possible condensation. Prolonged high surface
  RH may be relevant to mold risk, but risk also depends on the wall material,
  temperature and exposure time. This is <strong>not</strong> a direct measurement of
  moisture inside the wall.
</p>
